import type {
  Alert,
  EvacuationCenter,
  EvacuationHistoryRecord,
  Resident,
  StatCardData,
} from '../types/dashboard'
import { reportFileStamp, reportTimestamp } from './reportStamp'

type ExportReportArgs = {
  stats: StatCardData[]
  residents: Resident[]
  alerts: Alert[]
  evacuationCenters: EvacuationCenter[]
  evacuationHistory?: EvacuationHistoryRecord[]
  // Which data the report covers (a sitio name, or "All sitios").
  scopeLabel?: string
  // Who generated it, e.g. "Ana Alpha (Admin)".
  generatedBy?: string
}

// Main export function called when the user clicks the Export Report button.
export function exportReport({
  stats,
  residents,
  alerts,
  evacuationCenters,
  evacuationHistory = [],
  scopeLabel = 'Not specified',
  generatedBy = 'Not specified',
}: ExportReportArgs) {
  const generatedAt = new Date()
  const stamp = reportTimestamp(generatedAt)

  // Each section becomes part of the same CSV file.
  const reportSections = [
    [
      ['PriorityCare Report'],
      ['Generated', stamp.manila],
      ['Generated (UTC)', stamp.utc],
      ['Scope', scopeLabel],
      ['Generated by', generatedBy],
    ].map(formatCsvRow).join('\n'),
    buildSummarySection(stats),
    buildResidentsSection(residents),
    buildAlertsSection(alerts),
    buildEvacuationCentersSection(evacuationCenters),
    buildEvacuationHistorySection(evacuationHistory),
  ]

  const csvContent = reportSections.join('\n\n')
  const fileName = `prioritycare-report-${reportFileStamp(generatedAt)}.csv`

  downloadCsvFile(fileName, csvContent)
}

// Creates the Summary section of the CSV.
function buildSummarySection(stats: StatCardData[]) {
  const rows = [
    ['Summary'],
    ['Metric', 'Value', 'Note'],
    ...stats.map((stat) => [stat.label, String(stat.value), stat.note]),
  ]

  return rows.map(formatCsvRow).join('\n')
}

// Creates the Residents section of the CSV.
function buildResidentsSection(residents: Resident[]) {
  const rows = [
    ['Residents'],
    ['Name', 'Sitio', 'Constraint', 'Status', 'Flood Zone', 'Last Updated'],
    ...residents.map((resident) => [
      resident.name,
      resident.sitio,
      resident.constraint,
      resident.status,
      resident.floodZone ? 'Yes' : 'No',
      resident.lastUpdated,
    ]),
  ]

  return rows.map(formatCsvRow).join('\n')
}

// Creates the Alerts section of the CSV.
function buildAlertsSection(alerts: Alert[]) {
  const rows = [
    ['Alerts'],
    ['Title', 'Time', 'Priority'],
    ...alerts.map((alert) => [alert.title, alert.time, alert.priority]),
  ]

  return rows.map(formatCsvRow).join('\n')
}

// Creates the Evacuation Centers section of the CSV.
function buildEvacuationCentersSection(evacuationCenters: EvacuationCenter[]) {
  const rows = [
    ['Evacuation Centers'],
    ['Name', 'Capacity', 'Occupied', 'Status'],
    ...evacuationCenters.map((center) => [
      center.name,
      String(center.capacity),
      String(center.occupied),
      center.status,
    ]),
  ]

  return rows.map(formatCsvRow).join('\n')
}

// Creates the data mining history section of the CSV.
function buildEvacuationHistorySection(evacuationHistory: EvacuationHistoryRecord[]) {
  const rows = [
    ['Evacuation History / Data Mining'],
    [
      'Resident',
      'Sitio',
      'Constraint',
      'Status',
      'Evacuation Center',
      'Disaster Event',
      'Month',
      'Year',
      'Response Minutes',
      'Flood Zone',
    ],
    ...evacuationHistory.map((record) => [
      record.residentName,
      record.sitio,
      record.constraint,
      record.status,
      record.evacuationCenter,
      record.disasterEvent,
      record.month,
      String(record.year),
      String(record.responseMinutes),
      record.floodZone ? 'Yes' : 'No',
    ]),
  ]

  return rows.map(formatCsvRow).join('\n')
}

// Converts one array of values into a CSV row.
function formatCsvRow(values: string[]) {
  return values.map(formatCsvCell).join(',')
}

// Escapes quotes so commas and special characters do not break the CSV.
// Values starting with = + - @ (or a tab/carriage return) are prefixed with
// an apostrophe so spreadsheet apps do not run them as formulas; resident
// names and addresses come from public registration.
function formatCsvCell(value: string) {
  const safeValue = /^[=+\-@\t\r]/.test(value) ? `'${value}` : value
  const escapedValue = safeValue.replaceAll('"', '""')
  return `"${escapedValue}"`
}

// Creates a temporary link and clicks it to download the CSV file.
function downloadCsvFile(fileName: string, csvContent: string) {
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' })
  const url = URL.createObjectURL(blob)

  const link = document.createElement('a')
  link.href = url
  link.download = fileName
  link.click()

  URL.revokeObjectURL(url)
}

