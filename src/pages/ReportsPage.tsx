import { useEffect, useState } from 'react'
import type { StatCardData } from '../types/dashboard'
import { RdanaSummaryPanel } from '../components/RdanaSummaryPanel'
import { DromicExportPanel } from '../components/DromicExportPanel'
import { AuditTrailPanel } from '../components/AuditTrailPanel'
import { reportTimestamp } from '../utils/reportStamp'

type ReportsPageProps = {
  stats: StatCardData[]
  // The data the figures cover: a sitio name, or "All sitios".
  scopeLabel: string
  // Who is printing, e.g. "Ana Alpha (Admin)".
  generatedBy: string
}

export function ReportsPage({ stats, scopeLabel, generatedBy }: ReportsPageProps) {
  const [printedAt, setPrintedAt] = useState<{ manila: string; utc: string } | null>(null)
  const [printRequest, setPrintRequest] = useState(0)

  // Print after the timestamp has rendered into the printable header.
  useEffect(() => {
    if (printRequest > 0) window.print()
  }, [printRequest])

  function printSummary() {
    setPrintedAt(reportTimestamp())
    setPrintRequest((count) => count + 1)
  }

  // Uses the same stat data as the dashboard, but in a report-card layout.
  return (
    <>
    <div className="no-print">
      <DromicExportPanel />
      <RdanaSummaryPanel />
      <AuditTrailPanel />
    </div>
    <section className="panel printable-report">
      <div className="section-header">
        <div>
          <span className="panel-kicker">SUMMARY REPORT</span>
          <h3>Current dashboard figures</h3>
        </div>
        <button type="button" className="secondary-button no-print" onClick={printSummary}>
          Print Report
        </button>
      </div>

      {/* Only shown on paper: when, what scope, and by whom. */}
      <div className="print-only print-report-header">
        <h1>PriorityCare Summary Report</h1>
        <p><strong>Scope:</strong> {scopeLabel}</p>
        <p><strong>Generated:</strong> {printedAt?.manila ?? ''}</p>
        <p><strong>Generated (UTC):</strong> {printedAt?.utc ?? ''}</p>
        <p><strong>Generated by:</strong> {generatedBy}</p>
      </div>

      <div className="reports-grid">
        {stats.map((stat) => (
          <article className="report-card" key={stat.label}>
            <span>{stat.label}</span>
            <strong>{stat.value}</strong>
            <small>{stat.note}</small>
          </article>
        ))}
      </div>

      <p className="print-only print-report-note">
        Figures are the live values shown on the dashboard at the time above.
      </p>
    </section>
    </>
  )
}
